"""Build compact Latin/Greek UI fonts; keep full originals as fallback faces.
Requires fonttools[woff]. Run when the bundled source fonts change.
"""
from pathlib import Path
from fontTools import subset
ROOT = Path(__file__).resolve().parents[1]
RANGES = [(0,0x24f),(0x300,0x3ff),(0x2000,0x206f),(0x20ac,0x20ac),(0x2190,0x21ff),(0x2212,0x2212)]
faces=[]
def ranges(values):
    spans=[]
    for value in sorted(values):
        if spans and value==spans[-1][1]+1:spans[-1][1]=value
        else:spans.append([value,value])
    return ','.join('U+'+format(a,'X')+('-'+format(b,'X') if a!=b else '') for a,b in spans)
for name in ['libre','sans','serif']:
    options = subset.Options()
    options.flavor = 'woff2'
    options.recalc_timestamp = False
    font = subset.load_font(str(ROOT / 'fonts' / (name+'.woff2')), options)
    original=set(font.getBestCmap())
    worker = subset.Subsetter(options=options)
    worker.populate(unicodes=[u for a,b in RANGES for u in range(a,b+1)])
    worker.subset(font)
    target = ROOT / 'fonts/latin' / (name+'.woff2')
    target.parent.mkdir(exist_ok=True)
    subset.save_font(font, str(target), options)
    print(name, target.stat().st_size)
    kept=set(font.getBestCmap())
    families={'libre':['Libre','LibreDisplay'],'sans':['SourceSans'],'serif':['SourceSerif']}[name]
    for family in families:
        weight='font-weight:400 700;' if family=='LibreDisplay' else ''
        for file,points in [(name+'.woff2',original-kept),('latin/'+name+'.woff2',kept)]:
            if points:faces.append('@font-face{font-family:'+family+';src:url("../fonts/'+file+'") format("woff2");'+weight+'font-display:swap;unicode-range:'+ranges(points)+'}')
(ROOT / 'site/fonts.css').write_text('/* Generated by scripts/build-fonts.py; source fonts remain fallback. */\n'+'\n'.join(faces)+'\n')
